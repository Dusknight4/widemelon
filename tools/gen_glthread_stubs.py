#!/usr/bin/env python3
# Generates src/GLThreadStubs.inc from src/frontend/glad/glad.h: one stub per GL
# function, which GLThread installs over glad's function pointers so the calls
# run on the render thread. Run from the repository root:
#   python tools/gen_glthread_stubs.py
import re
import sys

GLAD = "src/frontend/glad/glad.h"
OUT = "src/GLThreadStubs.inc"

typedef_re = re.compile(r"^typedef (.+?) \(APIENTRYP (PFNGL[A-Z0-9_]+PROC)\)\((.*)\);$")
decl_re = re.compile(r"^GLAPI (PFNGL[A-Z0-9_]+PROC) glad_(gl[A-Za-z0-9_]+);$")

# Functions whose pointer arguments are copied into the queue (ASYNC with data):
# the C++ expression for the byte count, and which argument holds the data.
COPY = {
    "glBufferData": ("data", "data ? (size_t)size : 0"),
    "glBufferSubData": ("data", "data ? (size_t)size : 0"),
    "glDeleteTextures": ("textures", "(size_t)n * sizeof(GLuint)"),
    "glDeleteBuffers": ("buffers", "(size_t)n * sizeof(GLuint)"),
    "glDeleteFramebuffers": ("framebuffers", "(size_t)n * sizeof(GLuint)"),
    "glDeleteRenderbuffers": ("renderbuffers", "(size_t)n * sizeof(GLuint)"),
    "glDeleteVertexArrays": ("arrays", "(size_t)n * sizeof(GLuint)"),
    "glDeleteSamplers": ("samplers", "(size_t)count * sizeof(GLuint)"),
    "glDeleteQueries": ("ids", "(size_t)n * sizeof(GLuint)"),
    "glDrawBuffers": ("bufs", "(size_t)n * sizeof(GLenum)"),
    "glTexImage2D": ("pixels", "TexBytes(pixels, format, type, width, height, 1)"),
    "glTexImage3D": ("pixels", "TexBytes(pixels, format, type, width, height, depth)"),
    "glTexSubImage2D": ("pixels", "TexBytes(pixels, format, type, width, height, 1)"),
    "glTexSubImage3D": ("pixels", "TexBytes(pixels, format, type, width, height, depth)"),
    "glClearBufferfv": ("value", "ClearBufferBytes(buffer, sizeof(GLfloat))"),
    "glClearBufferiv": ("value", "ClearBufferBytes(buffer, sizeof(GLint))"),
    "glClearBufferuiv": ("value", "ClearBufferBytes(buffer, sizeof(GLuint))"),
}
for n, comps in (("1", 1), ("2", 2), ("3", 3), ("4", 4)):
    for t, ct in (("f", "GLfloat"), ("i", "GLint"), ("ui", "GLuint")):
        COPY[f"glUniform{n}{t}v"] = ("value", f"(size_t)count * {comps} * sizeof({ct})")
for m, comps in (("2", 4), ("3", 9), ("4", 16), ("2x3", 6), ("3x2", 6), ("2x4", 8), ("4x2", 8), ("3x4", 12), ("4x3", 12)):
    COPY[f"glUniformMatrix{m}fv"] = ("value", f"(size_t)count * {comps} * sizeof(GLfloat)")

# Pointer arguments that are really buffer offsets: passed by value.
OFFSET_PTR = {"glVertexAttribPointer", "glVertexAttribIPointer", "glDrawElements",
              "glDrawElementsBaseVertex", "glDrawRangeElements", "glDrawElementsInstanced"}

# Functions with hand-written stubs in GLThread.cpp (state tracking and caches).
CUSTOM = {"glGetUniformLocation", "glLinkProgram", "glDeleteProgram", "glBindBuffer",
          "glReadPixels", "glActiveTexture", "glBindTexture", "glGetTexLevelParameteriv",
          "glFinish"}

# Calls that (re)specify or delete textures: the texture size cache is cleared.
TEX_CHANGE = {"glTexImage1D", "glTexImage2D", "glTexImage3D", "glTexStorage1D", "glTexStorage2D",
              "glTexStorage3D", "glTexImage2DMultisample", "glTexImage3DMultisample",
              "glTexStorage2DMultisample", "glTexStorage3DMultisample", "glDeleteTextures", "glTexBuffer"}

def parse_params(s):
    s = s.strip()
    if s in ("", "void"):
        return []
    params = []
    for p in s.split(","):
        p = p.strip()
        m = re.match(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)$", p)
        typ, name = m.group(1).strip(), m.group(2)
        params.append((typ, name))
    return params

def main():
    typedefs = {}
    funcs = []
    with open(GLAD, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip()
            m = typedef_re.match(line)
            if m:
                typedefs[m.group(2)] = (m.group(1).strip(), parse_params(m.group(3)))
                continue
            m = decl_re.match(line)
            if m and m.group(1) in typedefs:
                funcs.append((m.group(2), m.group(1)))
    seen = set()
    out = ["// Generated by tools/gen_glthread_stubs.py from glad.h. Do not edit.", ""]
    install = []
    for name, pfn in funcs:
        if name in seen:
            continue
        seen.add(name)
        ret, params = typedefs[pfn]
        args = ", ".join(f"{t} {n}" for t, n in params)
        names = ", ".join(n for _, n in params)
        out.append(f"static {pfn} real_{name};")
        install.append(name)
        if name in CUSTOM:
            continue  # GLThread.cpp defines stub_<name>
        has_ptr = any("*" in t for t, _ in params)
        if ret != "void":
            body = f"    if (OnRenderThread()) return real_{name}({names});\n" \
                   f"    return Call([&] {{ return real_{name}({names}); }});"
        elif name in COPY:
            arg, size = COPY[name]
            caps = ", ".join(n for _, n in params if n != arg)
            call = ", ".join(("(" + t + ")(" + arg + " ? d : nullptr)") if n == arg else n for t, n in params)
            body = f"    if (OnRenderThread()) {{ real_{name}({names}); return; }}\n" \
                   f"    const size_t len = {size};\n" \
                   f"    if (len > kMaxCopy) {{ Call([&] {{ real_{name}({names}); }}); return; }}\n" \
                   f"    Enqueue([=](const void* d) {{ (void)d; real_{name}({call}); }}, {arg}, len);"
            if not caps:
                pass
        elif has_ptr and name not in OFFSET_PTR:
            body = f"    if (OnRenderThread()) {{ real_{name}({names}); return; }}\n" \
                   f"    Call([&] {{ real_{name}({names}); }});"
        else:
            body = f"    if (OnRenderThread()) {{ real_{name}({names}); return; }}\n" \
                   f"    Enqueue([=](const void*) {{ real_{name}({names}); }});"
        if name in TEX_CHANGE:
            body = "    OnTexChange();\n" + body
        out.append(f"static {ret} APIENTRY stub_{name}({args})\n{{\n{body}\n}}")
    out.append("")
    out.append("static void InstallStubs()\n{")
    for name in install:
        if name in CUSTOM:
            out.append(f"    real_{name} = glad_{name};   // stub in GLThread.cpp")
        else:
            out.append(f"    real_{name} = glad_{name}; if (real_{name}) glad_{name} = stub_{name};")
    out.append("}")
    out.append("")
    out.append("static void RemoveStubs()\n{")
    for name in install:
        out.append(f"    if (real_{name}) glad_{name} = real_{name};")
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(install)} functions")

if __name__ == "__main__":
    sys.exit(main())
